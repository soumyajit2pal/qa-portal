-- QA Workspaces: removes the one-QA-department ceiling while preserving the
-- existing COE - Quality Assurance team as the initial default workspace.
-- Safe to re-run. Apply before deploying code that references these columns.

BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE qap_qa_workspaces (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_key VARCHAR2(40) NOT NULL UNIQUE,
    name VARCHAR2(150) NOT NULL UNIQUE,
    description CLOB,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    is_default NUMBER(1) DEFAULT 0 NOT NULL,
    created_by_id NUMBER REFERENCES qap_users(id),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE qap_qa_workspace_members (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id NUMBER NOT NULL REFERENCES qap_qa_workspaces(id),
    user_id NUMBER NOT NULL REFERENCES qap_users(id),
    role VARCHAR2(40) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP,
    CONSTRAINT uq_qap_qawm_ws_user_role UNIQUE (workspace_id,user_id,role)
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE qap_qa_workspace_coverage (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id NUMBER NOT NULL REFERENCES qap_qa_workspaces(id),
    department_id NUMBER REFERENCES qap_departments(id),
    application_master_id NUMBER REFERENCES qap_application_master(id),
    request_type VARCHAR2(80),
    priority NUMBER DEFAULT 100 NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE qap_users ADD (preferred_qa_workspace_id NUMBER REFERENCES qap_qa_workspaces(id))';
